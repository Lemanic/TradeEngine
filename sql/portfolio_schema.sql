-- Portfolio module schema.
--
-- The prod profile runs with ddl-auto: validate, so these tables must exist before the
-- application starts. Run this once by hand against PostgreSQL:
--
--   psql -h localhost -U <user> -d postgres -f sql/portfolio_schema.sql
--
-- Dev (H2, ddl-auto: create) builds the same tables from the entities and needs nothing here.
-- Columns, types and scales mirror PortfolioSnapshotEntity / PortfolioPositionEntity exactly;
-- verified against Hibernate's own PostgreSQL DDL export. The only addition is ON DELETE CASCADE
-- on the FK, so deleting a snapshot by hand takes its positions with it.

CREATE TABLE portfolio_snapshot
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- One hour, one snapshot: a re-run for the same hour replaces the row.
    taken_at  TIMESTAMP WITH TIME ZONE NOT NULL UNIQUE,
    total_usd NUMERIC(38, 8)           NOT NULL,
    total_pln NUMERIC(38, 8)           NOT NULL,
    complete  BOOLEAN                  NOT NULL
);

CREATE TABLE portfolio_position
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT         NOT NULL REFERENCES portfolio_snapshot (id) ON DELETE CASCADE,
    source      VARCHAR(64)    NOT NULL,
    network     VARCHAR(64)    NOT NULL,
    asset       VARCHAR(32)    NOT NULL,
    cmc_id      INTEGER        NOT NULL,
    amount      NUMERIC(38, 18) NOT NULL,
    price_usd   NUMERIC(38, 18) NOT NULL,
    price_pln   NUMERIC(38, 18) NOT NULL,
    value_usd   NUMERIC(38, 8)  NOT NULL,
    value_pln   NUMERIC(38, 8)  NOT NULL,
    stale       BOOLEAN         NOT NULL
);

CREATE INDEX idx_portfolio_position_snapshot ON portfolio_position (snapshot_id);

-- Ilości pozycji wpisywanych ręcznie (BCH na Trezorze, staking TAO i TRB).
-- Konfiguracja decyduje, JAKIE pozycje istnieją; ta tabela trzyma ICH AKTUALNĄ ILOŚĆ,
-- bo zmienia ją PUT /api/portfolio/manual-holdings/{key} i musi przetrwać restart.
-- Wiersz powstaje sam przy starcie aplikacji, z wartością z konfiguracji jako ziarnem.
CREATE TABLE manual_holding
(
    holding_key VARCHAR(64) PRIMARY KEY,
    amount      NUMERIC(38, 18)          NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Fille z Hyperliquid, o których już powiadomiono na Telegramie.
-- Jedna tabela robi dwie rzeczy: tid nadany przez giełdę jest kluczem głównym (więc powtórny
-- odczyt tego samego filla nie wywoła drugiej wiadomości), a max(fill_time) jest kursorem dla
-- kolejnego zapytania userFillsByTime. Pusta tabela znaczy "pierwsze uruchomienie" — wtedy
-- fille z ostatnich godzin są zapisywane BEZ powiadamiania.
CREATE TABLE hyperliquid_fill
(
    tid         BIGINT PRIMARY KEY,
    fill_time   TIMESTAMP WITH TIME ZONE NOT NULL,
    coin        VARCHAR(64)              NOT NULL,
    notified_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_hyperliquid_fill_time ON hyperliquid_fill (fill_time DESC);
